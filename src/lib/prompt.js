export function buildUserContent({ title, language, transcript, truncated }) {
  const lines = [
    `제목: ${title || "제목 없음"}`,
    `자막 언어: ${language || "알 수 없음"}`,
  ];

  if (truncated) {
    lines.push(
      "참고: 영상이 길어 자막을 전체 길이에 걸쳐 균등하게 추렸습니다. 전달된 자막 안에서만 요약하세요.",
    );
  }

  lines.push("", "자막:", transcript);
  return lines.join("\n");
}
